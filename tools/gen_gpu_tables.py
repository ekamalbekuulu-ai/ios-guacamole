import re, os

ROOT = r"C:\hjkkik\ios7pro"
XML = os.path.join(ROOT, r"handoff\03-references-msm\a6xx.xml")
CAT = os.path.join(ROOT, r"work\gpu\ref\a6xx_catalog.c")
OUT = os.path.join(ROOT, r"ios-guacamole-main\xnu\sweet_gpu_tables.h")

# ---- 1. a6xx.xml: name -> dword offset (only inside the A6XX domain) ----
txt = open(XML, encoding='utf-8', errors='replace').read()
start = txt.find('<domain name="A6XX" ')
end = txt.find('</domain>', start)
domain = txt[start:end]
regmap = {}
for m in re.finditer(r'<reg32\s+offset="(0x[0-9a-fA-F]+)"\s+name="([A-Z0-9_]+)"', domain):
    off = int(m.group(1), 16)
    name = m.group(2)
    regmap.setdefault(name, off)
print("xml regs:", len(regmap))

cat = open(CAT, encoding='utf-8', errors='replace').read()

def block(name, opener):
    i = cat.find(opener)
    if i < 0:
        raise SystemExit("table not found: " + opener)
    j = cat.find("};", i)
    return cat[i:j]

# ---- 2. a640_hwcg ----
hw = block("a640_hwcg", "static const struct adreno_reglist a640_hwcg[] = {")
entries = []
missing = []
for m in re.finditer(r'\{\s*REG_A6XX_([A-Z0-9_]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}', hw):
    name, val = m.group(1), int(m.group(2), 16)
    if name in regmap:
        entries.append((regmap[name] * 4, val))
    else:
        missing.append(name)
print("a640_hwcg entries:", len(entries), "missing:", len(missing), missing[:5])

# ---- 3. a630_protect (a640 uses it) ----
pr = block("a630_protect", "static const u32 a630_protect_regs[] = {")
spans = []
for m in re.finditer(r'A6XX_PROTECT_(RDONLY|NORDWR)\((0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+)\)', pr):
    kind, a, b = m.group(1), int(m.group(2), 16), int(m.group(3), 16)
    spans.append((a, a + b, 0 if kind == 'RDONLY' else 1))
print("a630_protect spans:", len(spans))

# ---- 4. emit header ----
lines = []
lines.append("/*")
lines.append(" * a640 register tables, in the shape the K90/HackiOS driver uses")
lines.append(" * (adreno8_gpu.c: a8_protected[] spans and a8_ao_hwcg[] reg/value pairs).")
lines.append(" *")
lines.append(" * Values come from the authoritative Linux msm tables: a640_hwcg[] and the")
lines.append(" * a630_protect_regs[] span list (a640 selects a630_protect in a6xx_catalog.c).")
lines.append(" * Offsets are already converted from the a6xx.xml dword index to bytes, so")
lines.append(" * they can be handed straight to gpu_rd()/gpu_wr() on the GPU register base.")
lines.append(" *")
lines.append(" * Generated by tools/gen_gpu_tables.py - do not edit by hand.")
lines.append(" */")
lines.append("#ifndef _SWEET_GPU_TABLES_H_")
lines.append("#define _SWEET_GPU_TABLES_H_")
lines.append("")
lines.append("struct sweet_reg_val {")
lines.append("\tuint32_t off;")
lines.append("\tuint32_t val;")
lines.append("};")
lines.append("")
lines.append("/* CP_PROTECT span: start | ((end - start) << 18) | (noaccess << 31) */")
lines.append("struct sweet_protect_span {")
lines.append("\tuint32_t start;")
lines.append("\tuint32_t end;")
lines.append("\tuint32_t noaccess;")
lines.append("};")
lines.append("")
lines.append("static const struct sweet_reg_val sweet_a640_hwcg[] = {")
for off, val in entries:
    lines.append("\t{ 0x%05xu, 0x%08xu }," % (off, val))
lines.append("};")
lines.append("")
lines.append("static const struct sweet_protect_span sweet_a640_protect[] = {")
for a, b, na in spans:
    lines.append("\t{ 0x%05xu, 0x%05xu, %u }," % (a, b, na))
lines.append("};")
lines.append("")
lines.append("#define SWEET_A640_HWCG_COUNT\t\t%du" % len(entries))
lines.append("#define SWEET_A640_PROTECT_COUNT\t%du" % len(spans))
lines.append("")
lines.append("#endif /* _SWEET_GPU_TABLES_H_ */")

open(OUT, 'w', encoding='utf-8', newline='\n').write("\n".join(lines) + "\n")
print("wrote", OUT, len(lines), "lines")
